# Tax calculation utilities
def calculate_income_tax_individual(annual_income: float) -> dict:
    """
    Calculate Israeli income tax for individuals (self-employed dentists).
    
    Args:
        annual_income: Annual income in ILS
        
    Returns:
        Dictionary with tax breakdown
    """
    brackets = [
        (81480, 0.10),
        (116760, 0.14),
        (187440, 0.20),
        (260520, 0.31),
        (544320, 0.35),
        (721560, 0.47),
        (float('inf'), 0.50),
    ]
    
    tax = 0
    remaining = annual_income
    prev_bracket = 0
    
    breakdown = []
    
    for bracket_max, rate in brackets:
        if remaining <= 0:
            break
        
        taxable_in_bracket = min(remaining, bracket_max - prev_bracket)
        tax_in_bracket = taxable_in_bracket * rate
        
        tax += tax_in_bracket
        
        breakdown.append({
            'bracket': f'₪{prev_bracket:,.0f} - ₪{bracket_max:,.0f}',
            'rate': f'{rate*100:.0f}%',
            'taxable': taxable_in_bracket,
            'tax': tax_in_bracket,
        })
        
        remaining -= taxable_in_bracket
        prev_bracket = bracket_max
    
    effective_rate = (tax / annual_income * 100) if annual_income > 0 else 0
    
    return {
        'annual_income': annual_income,
        'total_tax': tax,
        'effective_rate': effective_rate,
        'net_income': annual_income - tax,
        'breakdown': breakdown,
    }


def calculate_income_tax_company(annual_income: float) -> dict:
    """
    Calculate Israeli corporate income tax.
    
    Args:
        annual_income: Annual income in ILS
        
    Returns:
        Dictionary with tax breakdown
    """
    rate = 0.23  # 23% flat rate for companies
    tax = annual_income * rate
    
    return {
        'annual_income': annual_income,
        'tax_rate': '23%',
        'total_tax': tax,
        'net_income': annual_income - tax,
    }


def calculate_vat(amount: float, is_exempt: bool = True) -> dict:
    """
    Calculate VAT for dental services.
    
    Args:
        amount: Service amount in ILS
        is_exempt: Whether the service is VAT-exempt (most dental treatments are)
        
    Returns:
        Dictionary with VAT breakdown
    """
    vat_rate = 0.17  # 17%
    
    if is_exempt:
        return {
            'amount': amount,
            'vat': 0,
            'total': amount,
            'status': 'פטור ממע"מ',
        }
    else:
        vat = amount * vat_rate
        return {
            'amount': amount,
            'vat': vat,
            'total': amount + vat,
            'status': f'חייב במע"מ ({vat_rate*100:.0f}%)',
        }


